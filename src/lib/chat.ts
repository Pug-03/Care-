import { analyze, FREQ_LABEL, OVERALL_LABEL, type Profile } from "./health";

/** Symptoms that need emergency care now, not a chat. Checked before anything is sent to the model. */
const RED_FLAGS = [
  /เจ็บ(แน่น)?หน้าอก|แน่นหน้าอก|เจ็บอก/,
  /หายใจ(ไม่ออก|ลำบาก|ติดขัด)/,
  /(แขน|ขา|หน้า).{0,6}(อ่อนแรง|ชา|เบี้ยว)|ปากเบี้ยว/,
  /พูด(ไม่ชัด|ลำบาก)/,
  /หมดสติ|ชัก|เป็นลม/,
  /(ไอ|อาเจียน)เป็นเลือด/,
  /ฆ่าตัวตาย|อยากตาย|ทำร้ายตัวเอง/,
];

export function redFlag(text: string) {
  return RED_FLAGS.some((r) => r.test(text));
}

export function isSelfHarm(text: string) {
  return /ฆ่าตัวตาย|อยากตาย|ทำร้ายตัวเอง/.test(text);
}

export function emergencyReply(text: string) {
  if (isSelfHarm(text))
    return "ขอบคุณที่บอกนะ ตอนนี้คุณไม่ได้อยู่คนเดียว หากรู้สึกไม่ปลอดภัย โทรสายด่วนสุขภาพจิต 1323 ได้ตลอด 24 ชั่วโมง หรือ 1669 หากเป็นเหตุฉุกเฉิน และลองบอกคนที่ไว้ใจให้อยู่ด้วยตอนนี้ ผมยังอยู่ตรงนี้ถ้าอยากเล่าต่อนะครับ";
  return "อาการที่คุณเล่ามาอาจเป็นภาวะฉุกเฉิน กรุณาโทร 1669 (บริการการแพทย์ฉุกเฉิน) หรือไปห้องฉุกเฉินที่ใกล้ที่สุดทันที อย่ารอดูอาการ และอย่าขับรถไปเองหากมีอาการรุนแรง";
}

/** Compact summary of the user's saved data, given to the model as context. */
export function profileContext(p: Profile | null) {
  if (!p) return "ผู้ใช้ยังไม่ได้กรอกข้อมูลสุขภาพในแอป";
  const a = analyze(p);
  const lines = [
    `ชื่อเล่น: ${p.name || "-"}, อายุ ${p.age} ปี, เพศ${p.sex === "male" ? "ชาย" : "หญิง"}`,
    `ส่วนสูง ${p.heightCm} ซม., น้ำหนัก ${p.weightKg} กก., BMI ${a.bmi}`,
    p.systolic ? `ความดัน ${p.systolic}/${p.diastolic}` : "ไม่มีค่าความดัน",
    `นอน ${p.sleepHours} ชม./คืน, ออกกำลังกาย ${p.exerciseDays} วัน/สัปดาห์`,
    `กินหวาน${FREQ_LABEL[p.sweet]}, เค็ม${FREQ_LABEL[p.salty]}, มัน${FREQ_LABEL[p.fatty]}, ผักผลไม้ ${p.veggies} ส่วน/วัน, น้ำ ${p.water} แก้ว/วัน`,
    `ความเครียด ${p.stress}/10, บุหรี่: ${p.smoking}, แอลกอฮอล์ ${p.alcohol} ดื่ม/สัปดาห์`,
    `ประวัติครอบครัว: ${[p.family.diabetes && "เบาหวาน", p.family.hypertension && "ความดันสูง", p.family.heart && "โรคหัวใจ"].filter(Boolean).join(", ") || "ไม่มี"}`,
    `ผลประเมินของแอป: ${OVERALL_LABEL[a.overallLevel]} (${a.overall}%), ${a.conditions.map((c) => `${c.label} ${c.score}%`).join(", ")}`,
    `ปัจจัยที่ควรใส่ใจ: ${
      a.factors
        .filter((f) => f.level !== "good")
        .map((f) => `${f.label} (${f.value})`)
        .join(", ") || "ไม่มี"
    }`,
  ];
  return lines.join("\n");
}

