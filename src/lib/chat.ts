/**
 * Offline responder used when no API key is configured, so the prototype still demos end to end.
 * Keyword-matched, grounded in the user's saved profile.
 */
export function offlineReply(text: string, p: Profile | null): string {
  if (redFlag(text)) return emergencyReply(text);
  const a = p ? analyze(p) : null;
  const t = text.toLowerCase();
  const has = (...k: string[]) => k.some((x) => t.includes(x));

  if (has("นอน", "หลับ", "ง่วง", "ตื่น"))
    return `การนอนน้อยกว่า 7 ชั่วโมงเป็นประจำ สัมพันธ์กับความดันสูง น้ำหนักขึ้น และน้ำตาลในเลือดสูงขึ้น${p ? ` ตอนนี้คุณนอนประมาณ **${p.sleepHours} ชม./คืน**` : ""}\n\nลองเริ่มแบบนี้:\n- เข้านอนเวลาเดิมทุกวัน รวมวันหยุด\n- วางมือถือ 30 นาทีก่อนนอน\n- งดกาแฟหลังบ่ายสอง\n\nปกติคุณเข้านอนกี่โมง และมีอะไรทำให้นอนดึกบ้าง?`;
  if (has("หวาน", "น้ำตาล", "ชานม", "กาแฟ", "ขนม", "เบาหวาน"))
    return `น้ำตาลส่วนเกินเพิ่มความเสี่ยง **เบาหวานชนิดที่ 2** และน้ำหนักเกิน${a ? ` ตอนนี้ความเสี่ยงเบาหวานของคุณอยู่ที่ประมาณ **${a.conditions.find((c) => c.id === "diabetes")!.score}%**` : ""}\n\n- สั่งเครื่องดื่ม "หวานน้อย" ลดน้ำตาลได้เกือบครึ่ง\n- เปลี่ยนเครื่องดื่มหวาน 1 แก้วต่อวันเป็นน้ำเปล่า\n- เดิน 10–15 นาทีหลังอาหาร ช่วยคุมน้ำตาลหลังมื้อ\n\nลองเปิด "จำลองอนาคต" แล้วปรับ "กินหวาน" ดูว่าความเสี่ยงเปลี่ยนไปแค่ไหน`;
  if (has("เค็ม", "ความดัน", "ปวดหัว", "โซเดียม"))
    return `ความดันโลหิตเกี่ยวข้องกับการกินเค็ม ความเครียด การนอน และน้ำหนัก${p?.systolic ? ` ค่าล่าสุดของคุณคือ **${p.systolic}/${p.diastolic}**${p.systolic >= 140 || (p.diastolic ?? 0) >= 90 ? " ซึ่งสูงกว่าเกณฑ์ ควรวัดซ้ำและพิจารณาพบแพทย์" : ""}` : ""}\n\n- ชิมก่อนปรุง ไม่เติมน้ำปลาเพิ่ม\n- ลดน้ำซุปและบะหมี่กึ่งสำเร็จรูป\n- วัดความดันเช้า–เย็นต่อเนื่อง 7 วัน แล้วดูค่าเฉลี่ย\n\nหากปวดหัวรุนแรงทันที ร่วมกับตามัวหรือแขนขาอ่อนแรง ให้โทร 1669`;
  if (has("เครียด", "กังวล", "เหนื่อย", "หมดไฟ"))
    return `ความเครียดสะสมทำให้นอนไม่หลับ กินมากขึ้น และความดันสูงขึ้นได้\n\n- หายใจแบบ 4-7-8 วันละ 5 นาที\n- พักสายตาและยืดตัวทุกชั่วโมง\n- ออกไปเดินรับแสงแดดตอนเช้า 10 นาที\n\nช่วงนี้มีเรื่องอะไรที่ทำให้เครียดเป็นพิเศษไหม? ถ้ารู้สึกหนักมาก โทรปรึกษาสายด่วนสุขภาพจิต 1323 ได้`;
  if (has("ออกกำลัง", "วิ่ง", "เดิน", "ยิม", "อ้วน", "น้ำหนัก", "ลดน้ำหนัก"))
    return `WHO แนะนำกิจกรรมระดับปานกลาง **150 นาทีต่อสัปดาห์**${p ? ` ตอนนี้คุณออกกำลังกาย **${p.exerciseDays} วัน/สัปดาห์**${a ? ` และ BMI **${a.bmi}**` : ""}` : ""}\n\n- เริ่มจากเดินเร็ว 15 นาทีหลังมื้อเย็น\n- ใช้บันไดแทนลิฟต์ 2–3 ชั้น\n- เพิ่มทีละ 5 นาทีทุกสัปดาห์\n\nช่วงเวลาไหนของวันที่คุณพอจะว่างที่สุด?`;
  if (has("บุหรี่", "สูบ"))
    return "บุหรี่เป็นปัจจัยเสี่ยงหลักของโรคหัวใจและหลอดเลือด ข่าวดีคือความเสี่ยงเริ่มลดลงตั้งแต่ปีแรกที่เลิก\n\n- ลดลงวันละ 1 มวน และตั้งวันเลิกที่ชัดเจน\n- หลีกเลี่ยงสถานการณ์ที่ทำให้อยากสูบ\n- โทรสายด่วนเลิกบุหรี่ **1600** ฟรี";
  if (has("หมอ", "โรงพยาบาล", "ตรวจ", "สิทธิ", "บัตรทอง", "ประกันสังคม"))
    return `ถ้าต้องการพบแพทย์ เปิดเมนู **"ถ้าควรพบแพทย์"** เพื่อค้นหาสถานพยาบาลใกล้คุณ เลือกตามสิทธิ (บัตรทอง ประกันสังคม ข้าราชการ) พร้อมดูเวลาเปิดและเอกสารที่ต้องเตรียม${a?.seeDoctor ? `\n\nจากข้อมูลของคุณ แนะนำให้ตรวจเพิ่มเติมเพราะ: ${a.seeDoctorReasons.join(", ")}` : ""}`;
  if (has("ความเสี่ยง", "ผล", "วิเคราะห์", "สุขภาพฉัน"))
    return a
      ? `จากข้อมูลของคุณ ความเสี่ยงโดยรวมอยู่ในระดับ **${OVERALL_LABEL[a.overallLevel]} (${a.overall}%)**\n\nสิ่งที่ควรใส่ใจก่อน:\n${
          a.factors
            .filter((f) => f.level === "high")
            .slice(0, 3)
            .map((f) => `- ${f.label}: ${f.note}`)
            .join("\n") || "- ไม่มีปัจจัยเสี่ยงสูง รักษาพฤติกรรมนี้ไว้"
        }\n\nดูรายละเอียดได้ที่ "AI วิเคราะห์" นะ`
      : `ยังไม่มีข้อมูลสุขภาพของคุณ ลองกรอก "ข้อมูลสุขภาพ" ประมาณ 3 นาที แล้วผมจะช่วยวิเคราะห์ให้ครับ`;

  return `ขอบคุณที่เล่าให้ฟังนะครับ ขอถามเพิ่มอีกนิดครับ:\n- อาการนี้เป็นมานานแค่ไหน และเป็นบ่อยแค่ไหน\n- ช่วงนี้นอนวันละกี่ชั่วโมง\n- กินอาหารหวาน มัน เค็มบ่อยไหม\n\nข้อมูลยิ่งครบ ผมยิ่งช่วยประเมินปัจจัยเสี่ยงได้ตรงขึ้น`;
}
